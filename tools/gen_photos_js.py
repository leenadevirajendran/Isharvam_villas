#!/usr/bin/env python3
"""Writes assets/js/photos.js (slot -> Pexels photo id) and assets/img/CREDITS.md from tools/photo_manifest.py. remote=true loads the photos straight from Pexels until you download them."""
import os, sys, json
sys.path.insert(0, os.path.dirname(__file__)); import photo_manifest as P
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); m = P.all_slots()
js = '''/* ISHARVAM VILLAS: temporary demonstration photographs (Pexels, free to use). Generated by tools/gen_photos_js.py.
   remote: true  = photos load from the Pexels CDN (needs internet). Run `python3 tools/fetch_photos.py` once to download them as local WebP; it then sets remote to false.
   To use the client's own photos later: drop files with the same names in assets/img/ and set remote to false (or empty the map). */
window.ISH_PHOTOS = { remote: true, map: %s };
''' % json.dumps(m, separators=(',', ':'))
open(os.path.join(ROOT, 'assets/js/photos.js'), 'w').write(js)
c = ['# Temporary photograph credits\n\nDemonstration photographs from Pexels (free to use, attribution not required; see https://www.pexels.com/license/). Replace with the client\'s own photography.\n\n']
for k, i in sorted(m.items()): c.append('- %s: https://www.pexels.com/photo/%d/\n' % (k, i))
open(os.path.join(ROOT, 'assets/img/CREDITS.md'), 'w').write(''.join(c)); print(len(m), 'slots')
